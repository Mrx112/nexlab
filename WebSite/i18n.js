  const localeKey = "nexlab-website-language";
  const language = () => localStorage.getItem(localeKey) === "id" ? "id" : "en";
  const reverseCandidates = new Map();
  for (const [source, target] of Object.entries(translations)) {
    if (source === target) continue;
    reverseCandidates.set(target, reverseCandidates.has(target) ? null : source);
  }
  const dictionaries = {
    en: translations,
    id: Object.fromEntries([...reverseCandidates].filter(([, source]) => source !== null))
  };
  const keys = Object.fromEntries(Object.entries(dictionaries).map(([locale, table]) => [
    locale,
    Object.keys(table).sort((a, b) => b.length - a.length)
  ]));

  function translate(root) {
    const locale = language();
    const table = dictionaries[locale];
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      if (node.parentElement && node.parentElement.closest('script,style,pre,code,[translate="no"]')) continue;
      const source = node.nodeValue.trim();
      if (table[source]) {
        node.nodeValue = node.nodeValue.replace(source, table[source]);
      } else {
        let value = node.nodeValue;
        for (const key of keys[locale]) {
          if (key.length >= 5 && value.includes(key)) value = value.split(key).join(table[key]);
        }
        node.nodeValue = value;
      }
    }
    const elements = root instanceof Element ? [root, ...root.querySelectorAll("*")] : [];
    for (const element of elements) {
      if (element.matches('script,style,pre,code,[translate="no"]')) continue;
      for (const attr of ["placeholder", "aria-label", "title", "content"]) {
        if (attr === "content" && !element.matches('meta[name="description"]')) continue;
        const source = element.getAttribute(attr);
        if (source && table[source]) element.setAttribute(attr, table[source]);
      }
    }
  }

  function applyLanguage(value) {
    const next = value === "id" ? "id" : "en";
    localStorage.setItem(localeKey, next);
    document.documentElement.lang = next;
    document.querySelectorAll("#language-select").forEach(select => { select.value = next; });
    location.reload();
  }

  document.addEventListener("DOMContentLoaded", () => {
    const select = document.querySelector("#language-select");
    const saved = language();
    document.documentElement.lang = saved;
    translate(document.head);
    if (select) {
      select.value = saved;
      select.addEventListener("change", () => applyLanguage(select.value));
    }
    translate(document.body);
    new MutationObserver(records => records.forEach(record => {
      record.addedNodes.forEach(node => {
        if (node.nodeType === Node.ELEMENT_NODE) translate(node);
        else if (node.nodeType === Node.TEXT_NODE) translate(node.parentElement || document.body);
      });
    })).observe(document.body, { childList: true, subtree: true });
  });
